"""Read-only legacy memory records, checked against an independent integer oracle.

Source, executable model and generated bytecode must agree with manually encoded
field order, narrow cleanup, defaults, constants and exact revert payloads.
"""
import argparse
import json
from pathlib import Path
import random

from eth_utils import keccak
from .engine import HarnessError, write_json
from .check_legacy_signed_scalars import signed
from .check_legacy_state_transitions import campaign, word, error, SENDER

FIXTURE = Path('Contracts/SolidityImportSmoke/LegacyMemoryStructs.sol')
MODULUS = 1 << 256
FUNCTIONS = [f'{name}(uint256,uint256,int256)' for name in ('positional', 'named', 'captured')]
FUNCTIONS += ['defaults()', 'unary(uint256)', 'qualified(int24,int24)']


def scenario(kind, caller, layout, **_):
    initial = [[caller, word(int(f['slot'])), word(0xBEEF)] for f in layout['storage']]
    initial += [[caller, word(9999), word(0xC0FFEE)]]
    calls, expected = [], {}
    def add(signature, values, truncated=False):
        name = signature.split('(')[0]
        raw = b''.join((v % MODULUS).to_bytes(32, 'big') for v in values)
        reason = None
        if name == 'qualified':
            a, b = (signed(v, 24) for v in values)
            if kind == 'struct-v2' and any(v % MODULUS != x % MODULUS
                    for v, x in zip(values, (a, b))):
                reason = ''
            elif a > b:
                reason = 'order'
            elif a < -400:
                reason = 'low'
            elif b > 400:
                reason = 'high'
            result = [-400, 400]
        elif name == 'unary':
            result = [signed(-signed(values[0], 24), 24), 0, (~values[0]) % 256]
        elif name == 'defaults':
            result = [0] * 7
        else:
            a, b, d = values
            result = [a % (1 << 160), signed(a, 24), signed(b, 24), signed(d, 128),
                      b % 256, 1, 0x12345678 << 224]
        if truncated:
            raw = raw[:-1]
            reason = ''
        ident = str(len(calls))
        calls.append(dict(id=ident, label=name, function=name,
            args=[int.from_bytes(raw[i:i+32].ljust(32, b'\0'), 'big')
                  for i in range(0, len(raw), 32)], sender=SENDER, target=caller, value='0x0',
            data='0x'+(keccak(text=signature)[:4]+raw).hex(),
            timestamp=1000000100+len(calls), blockNumber=2+len(calls)))
        expected[ident] = dict(status='ok' if reason is None else 'revert',
            data='0x'+''.join(word(v % MODULUS)[2:] for v in result) if reason is None
                 else error(reason) if reason else '0x', events=[], storage=initial)
    rng = random.Random(760071)
    values = [(0, 0, 0), (1, 2, -1), ((1 << 23)-1, 1 << 23, -(1 << 127)),
              (MODULUS-1, 0, (1 << 127)-1), (1 << 200, MODULUS-1, 1 << 127),
              (1 << 160, 255, -(1 << 127)-1)]
    values += [tuple(rng.getrandbits(256) for _ in range(3)) for _ in range(12)]
    for signature in FUNCTIONS[:3]:
        for row in values:
            add(signature, row)
        add(signature, (0, 0, 0), truncated=True)
    add('defaults()', [])
    for a in [0, 1, 255, (1 << 23)-1, 1 << 23, MODULUS-1]:
        add('unary(uint256)', [a])
    for a, b in [(-400,400),(-401,400),(-400,401),(0,0),(1,0),(-1,1),
                 (1 << 23,0),(MODULUS-1,0),((1 << 24)-1,1),(-400,-400),(400,400)]:
        add('qualified(int24,int24)', [a,b])
    add('qualified(int24,int24)', [0,0], truncated=True)
    return initial, calls, expected


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--prepared', action='store_true')
    parser.add_argument('--optimized', action='store_true')
    parser.add_argument('--abi-v2', action='store_true')
    parser.add_argument('--context', type=int, choices=(0,1,2), default=0)
    parser.add_argument('--mutation', choices=('field-order', 'sign-cleanup'))
    args = parser.parse_args()
    out, fixture = args.output.resolve(), FIXTURE
    if args.mutation or args.abi_v2:
        out.parent.mkdir(parents=True, exist_ok=True)
        fixture = out.with_suffix('.sol')
        if fixture.exists():
            raise HarnessError('candidate source already exists')
        source = FIXTURE.read_text()
        if args.abi_v2:
            source = source.replace('pragma solidity 0.7.6;',
                                    'pragma solidity 0.7.6; pragma abicoder v2;')
        if args.mutation:
            marker, replacement = {
                'field-order': ('int24(a), int24(b), int128(d)', 'int24(b), int24(a), int128(d)'),
                'sign-cleanup': ('int128(d)', 'int128(uint128(uint24(d)))'),
            }[args.mutation]
            if marker not in source:
                raise HarnessError('record mutation anchor missing')
            source = source.replace(marker, replacement)
        fixture.write_text(source)
    result = campaign(out, kind='struct-v2' if args.abi_v2 else 'struct-v1',
        contract=FIXTURE.stem, fixture=fixture, functions=FUNCTIONS,
        scenario_builder=scenario, context=args.context, optimized=args.optimized,
        optimizer_runs=800, prepared=args.prepared)
    report = json.loads((out/'results.json').read_text())
    if args.mutation:
        witnesses = {route: [row['id'] for row in report['expectationMismatches']
            if row['route'] == route and row['field'] == 'data']
            for route in ('source','model','compiled')}
        if report['divergences'] or not all(witnesses.values()):
            raise HarnessError('record mutation lacks completed counterexamples on every route')
    elif result:
        raise HarnessError('memory record observations differ from the independent oracle')
    write_json(out/'complete.json', dict(optimized=args.optimized, abi_v2=args.abi_v2,
        context=args.context, mutation=args.mutation))
    print('memory record checks passed' if not args.mutation else 'memory record mutation detected')


if __name__ == '__main__':
    main()
